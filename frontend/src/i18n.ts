export type MessageKey = keyof typeof messages.zh

export function translate(language: Language, key: MessageKey, vars?: Vars): string {
  let value: string = messages[language][key] ?? messages.zh[key] ?? key
  if (vars) for (const [name, replacement] of Object.entries(vars)) value = value.replaceAll(`{${name}}`, String(replacement))
  return value
}

